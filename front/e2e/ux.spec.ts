import { expect, test } from '@playwright/test'

test.use({ timezoneId: 'Asia/Tokyo', reducedMotion: 'reduce' })
test('máscara, estratégias, saída protegida e data no fuso da empresa', async ({ page, request }, info) => {
  const slug = `ux-${info.project.name}-${Date.now()}`
  const email = `${slug}@example.com`
  const password = 'ux-password-123'
  await request.post('/api/companies', { data: { company: { name: 'Ateliê UX', slug, currency: 'EUR', timezone: 'America/Sao_Paulo' }, admin: { name: 'Ana', username: 'ana', email, password } } })
  await page.goto('/login')
  await page.getByLabel('Email', { exact: true }).fill(email)
  await page.getByLabel('Senha', { exact: true }).fill(password)
  await page.getByRole('button', { name: 'Entrar na minha conta' }).click()
  await page.getByRole('link', { name: /Cadastrar material/ }).click()
  await page.getByLabel('Nome', { exact: true }).fill('Resina')
  await page.getByLabel('Unidade de compra').selectOption('kg')
  const cost = page.getByLabel('Custo da compra')
  await cost.fill('')
  await cost.pressSequentially('1234')
  await expect(cost).toHaveValue('12,34')
  await cost.press('ControlOrMeta+A')
  await cost.pressSequentially('7000')
  await expect(cost).toHaveValue('70,00')
  await page.screenshot({ path: info.outputPath('ux-eur-material.png'), fullPage: true })
  await page.getByRole('button', { name: 'Salvar material' }).click()
  await expect(page.getByText('€ 70,00', { exact: true })).toBeVisible()
  await page.goto('/precificacao/nova')
  await page.getByLabel('Acréscimo (%)').fill('37,5')
  await page.getByRole('button', { name: /Acréscimo sobre custo/ }).click()
  await expect(page.getByLabel('Acréscimo (%)')).toHaveValue('37,5')
  await page.getByRole('button', { name: /Multiplicar o custo/ }).click()
  await page.getByRole('button', { name: /Acréscimo sobre custo/ }).click()
  await expect(page.getByLabel('Acréscimo (%)')).toHaveValue('37,5')
  await page.getByRole('button', { name: 'Cancelar edição' }).click()
  await page.getByRole('button', { name: 'Descartar e sair' }).click()
  await expect(page.getByRole('heading', { name: 'Regras de precificação', exact: true })).toBeVisible()
})

test('resultado anterior, máscara e navegação com alterações', async ({ page, request }, info) => {
  const slug = `ux-preview-${info.project.name}-${Date.now()}`
  const email = `${slug}@example.com`
  const password = 'ux-password-123'
  await request.post('/api/companies', { data: { company: { name: 'Ateliê UX', slug, currency: 'USD', timezone: 'America/Sao_Paulo' }, admin: { name: 'Ana', username: 'ana', email, password } } })
  await page.goto('/login')
  await page.getByLabel('Email', { exact: true }).fill(email)
  await page.getByLabel('Senha', { exact: true }).fill(password)
  await page.getByRole('button', { name: 'Entrar na minha conta' }).click()
  await page.getByRole('link', { name: /Testar uma regra/ }).click()
  const cost = page.getByLabel('Custo para testar')
  await cost.clear(); await cost.pressSequentially('1234')
  await expect(cost).toHaveValue('12,34')
  await expect(page.locator('.metric-value')).toContainText('US$ 16,05')
  await page.getByLabel('Acréscimo (%)').fill('37,5')
  await page.getByRole('button', { name: /Acréscimo sobre custo/ }).click()
  await expect(page.getByLabel('Acréscimo (%)')).toHaveValue('37,5')
  await page.getByRole('button', { name: /Multiplicar o custo/ }).click()
  await page.getByRole('button', { name: /Acréscimo sobre custo/ }).click()
  await expect(page.getByLabel('Acréscimo (%)')).toHaveValue('37,5')
  await page.screenshot({ path: info.outputPath('ux-usd-rule.png'), fullPage: true })
  await page.goBack()
  await expect(page.getByRole('dialog', { name: 'Descartar alterações?' })).toBeVisible()
  await page.getByRole('button', { name: 'Continuar editando' }).click()
  await expect(page.getByLabel('Acréscimo (%)')).toHaveValue('37,5')
  await page.goBack()
  await page.getByRole('button', { name: 'Descartar e sair' }).click()
  await expect(page.getByRole('heading', { name: /Olá/ })).toBeVisible()
  await page.getByRole('link', { name: 'Registrar venda' }).click()
  await page.getByLabel('Descrição da venda').fill('Data em Brasília')
  await page.getByLabel('Data da venda').fill('2026-09-23T10:00')
  const saved = page.waitForRequest(req => req.method() === 'POST' && req.url().endsWith('/sales'))
  await page.getByRole('button', { name: 'Salvar rascunho' }).click()
  expect((await saved).postDataJSON().occurred_at).toBe('2026-09-23T13:00:00.000Z')
  await expect(page.getByRole('heading', { name: 'Data em Brasília' })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})
