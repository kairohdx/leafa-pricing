import { expect, test } from '@playwright/test'

test('composição, conversão, sugestão e preço manual preservado no histórico', async ({ page, request }, info) => {
  const slug = `pricing-${info.project.name}-${Date.now()}`
  const email = `${slug}@example.com`
  const password = 'pricing-password-123'
  expect((await request.post('/api/companies', { data: { company: { name: 'Precificação', slug }, admin: { name: 'Ana', username: 'ana', email, password } } })).status()).toBe(201)
  const auth = await (await request.post('/api/auth/login', { data: { email, password } })).json()
  const headers = { Authorization: `Bearer ${auth.access_token}` }
  const material = await (await request.post('/api/materials', { headers, data: { name: 'Resina', purchase_unit_code: 'kg', purchase_quantity: '1', purchase_cost: '70' } })).json()
  const product = await (await request.post('/api/products', { headers, data: { name: 'Peça de resina' } })).json()
  expect((await request.post(`/api/products/${product.id}/materials`, { headers, data: { material_id: material.id, quantity: '500', unit_code: 'g' } })).status()).toBe(201)
  const rule = await (await request.post('/api/pricing-rules', { headers, data: { name: 'Acréscimo 30%', strategy_key: 'markup_percent', parameters: { percentage: '30', rounding: 'ending_90' } } })).json()
  await page.goto('/login')
  await page.getByLabel('Email', { exact: true }).fill(email)
  await page.getByLabel('Senha', { exact: true }).fill(password)
  await page.getByRole('button', { name: 'Entrar na minha conta' }).click()
  await expect(page.getByRole('button', { name: 'Sair da conta' })).toBeVisible()
  await page.goto(`/produtos/${product.id}`)
  await expect(page.getByRole('heading', { name: 'Custo da composição' })).toBeVisible()
  await page.getByText('Ver cálculo detalhado').click()
  await expect(page.getByText(/Custo proporcional: R\$ 35/)).toBeVisible()
  await page.goto('/vendas/nova')
  await page.getByLabel('Descrição da venda').fill('Venda calculada')
  await page.getByRole('button', { name: 'Escolher regra', exact: true }).click()
  await page.getByRole('button', { name: 'Acréscimo 30%', exact: true }).click()
  await page.getByRole('button', { name: 'Adicionar item', exact: true }).click()
  await page.getByLabel('Tipo de item').selectOption('product')
  await page.getByRole('button', { name: 'Peça de resina', exact: true }).click()
  await page.getByLabel('Quantidade do item 1').fill('2')
  await expect(page.getByText('Total sugerido: R$ 91,80')).toBeVisible()
  await page.getByRole('button', { name: 'Usar total sugerido' }).click()
  await expect(page.getByLabel('Valor cobrado')).toHaveValue('91,80')
  await page.getByLabel('Valor cobrado').fill('8000')
  await page.getByRole('button', { name: 'Salvar rascunho' }).click()
  await expect(page.getByRole('heading', { name: 'Venda calculada', exact: true })).toBeVisible()
  const id = page.url().split('/vendas/')[1]
  const original = await (await request.get(`/api/sales/${id}`, { headers })).json()
  expect(original.cost_total).toBe('70.00')
  expect(original.suggested_total).toBe('91.80')
  expect(original.final_total).toBe('80.00')
  await page.getByRole('button', { name: 'Concluir venda', exact: true }).click()
  await page.getByRole('dialog').getByRole('button').last().click()
  await expect(page.getByText(/^Concluída ·/)).toBeVisible()
  await request.patch(`/api/materials/${material.id}`, { headers, data: { purchase_cost: '200' } })
  await request.patch(`/api/pricing-rules/${rule.id}`, { headers, data: { expected_version: 1, parameters: { percentage: '50' } } })
  await page.reload()
  const preserved = await (await request.get(`/api/sales/${id}`, { headers })).json()
  expect(preserved.pricing_snapshot).toEqual(original.pricing_snapshot)
  expect(preserved.lines).toEqual(original.lines)
  await expect(page.getByText('R$ 80,00', { exact: true })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
})
