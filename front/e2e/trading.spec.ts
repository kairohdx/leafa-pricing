import { expect, test, type APIRequestContext, type Page } from '@playwright/test'

const password = 'trading-password-123'
async function account(page: Page, request: APIRequestContext, tag: string) {
  const slug = `${tag}-${Date.now()}-${Math.floor(Math.random() * 10000)}`
  const email = `${slug}@example.com`
  expect((await request.post('/api/companies', { data: { company: { name: 'Ateliê de vendas', slug }, admin: { name: 'Clara', username: 'clara', email, password } } })).status()).toBe(201)
  await login(page, email)
  const token = await page.evaluate(() => JSON.parse(sessionStorage.getItem('leafa.session')!).access_token as string)
  return { headers: { Authorization: `Bearer ${token}` }, email }
}
async function login(page: Page, email: string) {
  await page.goto('/login')
  await page.getByLabel('Email', { exact: true }).fill(email)
  await page.getByLabel('Senha', { exact: true }).fill(password)
  await page.getByRole('button', { name: 'Entrar na minha conta' }).click()
  await expect(page.getByRole('button', { name: 'Sair da conta' })).toBeVisible()
}
async function confirm(page: Page, action: string) {
  await page.getByRole('button', { name: action, exact: true }).click()
  await page.getByRole('button', { name: 'Confirmar', exact: true }).click()
  await expect(page.getByRole('dialog')).not.toBeVisible()
}

test('regras: JSON, padrão, conflito de versão, arquivo e restauração', async ({ page, request }, info) => {
  const { headers } = await account(page, request, `rules-${info.project.name}`)
  const previous = await (await request.post('/api/pricing-rules', { headers, data: { name: 'Anterior', strategy_key: 'manual', is_default: true } })).json()
  await page.goto('/precificacao/nova')
  await page.getByLabel('Nome da regra').fill('Margem de referência')
  await page.getByLabel('Identificador da estratégia').fill('manual')
  await page.getByLabel('Parâmetros (JSON)').fill('[]')
  await page.getByRole('button', { name: 'Salvar regra' }).click()
  await expect(page.getByText(/Informe um objeto JSON válido/)).toBeVisible()
  await page.getByLabel('Parâmetros (JSON)').fill('{"margem":"0.30"}')
  await page.getByLabel('Regra padrão').check()
  await page.getByRole('button', { name: 'Salvar regra' }).click()
  await expect(page.getByRole('heading', { name: 'Margem de referência', exact: true })).toBeVisible()
  const id = page.url().split('/precificacao/')[1]
  const get = async () => (await request.get(`/api/pricing-rules/${id}`, { headers })).json()
  expect((await (await request.get(`/api/pricing-rules/${previous.id}`, { headers })).json()).is_default).toBe(false)
  await page.getByRole('button', { name: 'Editar regra' }).click()
  await page.getByLabel('Nome da regra').fill('Minha edição preservada')
  expect((await request.patch(`/api/pricing-rules/${id}`, { headers, data: { expected_version: 1, name: 'Outra sessão' } })).status()).toBe(200)
  await page.getByRole('button', { name: 'Salvar regra' }).click()
  await expect(page.getByRole('alert')).toContainText('Seu texto foi preservado')
  await expect(page.getByLabel('Nome da regra')).toHaveValue('Minha edição preservada')
  expect((await get()).name).toBe('Outra sessão')
  await confirm(page, 'Recarregar regra')
  await expect(page.getByRole('heading', { name: 'Outra sessão', exact: true })).toBeVisible()
  await confirm(page, 'Arquivar')
  expect((await get()).is_default).toBe(false)
  await confirm(page, 'Restaurar')
  expect((await get()).is_default).toBe(false)
  await page.getByRole('button', { name: 'Editar regra' }).click()
  await page.getByLabel('Regra padrão').check()
  await page.getByRole('button', { name: 'Salvar regra' }).click()
  await expect(page.getByText(/Versão .*Padrão/)).toBeVisible()
  await page.screenshot({ path: info.outputPath('regra.png'), fullPage: true })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
})

test('venda: itens, snapshots, moeda histórica, total zero e transições', async ({ page, request }, info) => {
  test.setTimeout(60_000)
  const { headers } = await account(page, request, `sales-${info.project.name}`)
  const service = await (await request.post('/api/services', { headers, data: { name: 'Instalação original', base_price: '25.50' } })).json()
  const material = await (await request.post('/api/materials', { headers, data: { name: 'Resina para venda', purchase_unit_code: 'kg', purchase_quantity: '1', purchase_cost: '20' } })).json()
  await request.post('/api/products', { headers, data: { name: 'Produto pronto' } })
  const rule = await (await request.post('/api/pricing-rules', { headers, data: { name: 'Regra da venda', strategy_key: 'manual', parameters: { rate: '0.30' }, is_default: true } })).json()
  await page.goto('/vendas/nova')
  await page.getByLabel('Descrição da venda').fill('Encomenda especial')
  await page.getByLabel('Data e hora com fuso').fill('2026-09-16T14:30:00-03:00')
  await page.getByLabel('Total final manual').fill('9007199254740993,01')
  await expect(page.getByText('Sem regra', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Escolher regra', exact: true }).click()
  await page.getByRole('button', { name: 'Regra da venda', exact: true }).click()
  for (const [kind, name] of [['service', 'Instalação original'], ['material', 'Resina para venda'], ['product', 'Produto pronto']]) {
    await page.getByRole('button', { name: 'Adicionar item', exact: true }).click()
    await page.getByLabel('Tipo de item').selectOption(kind)
    await page.getByRole('button', { name, exact: true }).click()
  }
  await page.getByLabel('Quantidade do item 2').fill('0,123456')
  await expect(page.getByLabel('Unidade do item 2').locator('option[value="m"]')).toHaveCount(0)
  await page.getByLabel('Unidade do item 2').selectOption('g')
  await page.getByRole('button', { name: 'Salvar rascunho' }).click()
  await expect(page.getByRole('heading', { name: 'Encomenda especial', exact: true })).toBeVisible()
  const id = page.url().split('/vendas/')[1]
  const get = async () => (await request.get(`/api/sales/${id}`, { headers })).json()
  const original = await get()
  expect(original.final_total).toBe('9007199254740993.01')
  expect(original.lines).toHaveLength(3)
  await request.patch(`/api/services/${service.id}`, { headers, data: { name: 'Instalação atual', base_price: '99' } })
  await request.patch(`/api/pricing-rules/${rule.id}`, { headers, data: { expected_version: 1, parameters: { rate: '0.50' } } })
  await request.patch('/api/companies/me', { headers, data: { currency: 'USD' } })
  await page.reload()
  await page.getByRole('button', { name: 'Editar rascunho' }).click()
  await page.getByLabel('Descrição da venda').fill('Encomenda revisada')
  const patchPromise = page.waitForRequest((req) => req.method() === 'PATCH' && req.url().includes(`/sales/${id}`))
  await page.getByRole('button', { name: 'Salvar rascunho' }).click()
  expect((await patchPromise).postDataJSON()).toEqual({ description: 'Encomenda revisada' })
  await expect(page.getByRole('heading', { name: 'Encomenda revisada', exact: true })).toBeVisible()
  const preserved = await get()
  expect(preserved.lines).toEqual(original.lines)
  expect(preserved.pricing_snapshot).toEqual(original.pricing_snapshot)
  expect(preserved.currency).toBe('BRL')
  await page.getByRole('button', { name: 'Editar rascunho' }).click()
  await page.getByLabel('Quantidade do item 1').fill('2')
  await page.getByRole('button', { name: 'Remover item 3', exact: true }).click()
  await page.getByRole('button', { name: 'Remover regra', exact: true }).click()
  await page.getByLabel('Total final manual').fill('0')
  await page.getByRole('button', { name: 'Salvar rascunho' }).click()
  await expect(page.getByRole('heading', { name: 'Instalação atual', exact: true })).toBeVisible()
  const replaced = await get()
  expect(replaced.lines).toHaveLength(2)
  expect(replaced.lines[0].id).not.toBe(original.lines[0].id)
  expect(replaced.pricing_snapshot).toBeNull()
  await request.post(`/api/materials/${material.id}/archive`, { headers })
  await confirm(page, 'Concluir venda')
  await expect(page.getByText(/^Concluída ·/)).toBeVisible()
  await expect(page.getByRole('button', { name: 'Editar rascunho' })).toHaveCount(0)
  await expect(page.getByText('BRL 0,00', { exact: true })).toBeVisible()
  await page.screenshot({ path: info.outputPath('venda.png'), fullPage: true })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await confirm(page, 'Cancelar venda')
  await expect(page.getByText(/^Cancelada ·/)).toBeVisible()
  await expect(page.getByRole('button', { name: 'Concluir venda' })).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Cancelar venda' })).toHaveCount(0)
})

test('operador cria e conclui, sem cancelar ou editar regras; isolamento por empresa', async ({ page, request }, info) => {
  const { headers, email } = await account(page, request, `role-${info.project.name}`)
  const rule = await (await request.post('/api/pricing-rules', { headers, data: { name: 'Somente consulta', strategy_key: 'manual' } })).json()
  const service = await (await request.post('/api/services', { headers, data: { name: 'Serviço disponível', base_price: '10' } })).json()
  expect((await request.post('/api/users', { headers, data: { name: 'Operador', username: 'op', email: `op-${email}`, password } })).status()).toBe(201)
  await page.getByRole('button', { name: 'Sair da conta' }).click()
  await expect(page.getByRole('heading', { name: 'Bom ter você aqui.' })).toBeVisible()
  await login(page, `op-${email}`)
  const adminLogin = await request.post('/api/auth/login', { data: { email, password } })
  expect(adminLogin.status()).toBe(200)
  const adminHeaders = { Authorization: `Bearer ${(await adminLogin.json()).access_token}` }
  await page.goto(`/precificacao/${rule.id}`)
  await expect(page.getByRole('heading', { name: 'Somente consulta', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Editar regra' })).toHaveCount(0)
  await page.goto('/precificacao/nova')
  await expect(page.getByRole('heading', { name: 'Acesso restrito' })).toBeVisible()
  await page.goto('/vendas/nova')
  await page.getByLabel('Descrição da venda').fill('Venda do operador')
  await page.getByRole('button', { name: 'Salvar rascunho' }).click()
  await expect(page.getByRole('button', { name: 'Concluir venda' })).toBeDisabled()
  const id = page.url().split('/vendas/')[1]
  await page.getByRole('button', { name: 'Editar rascunho' }).click()
  await page.getByRole('button', { name: 'Adicionar item', exact: true }).click()
  await page.getByRole('button', { name: 'Serviço disponível', exact: true }).click()
  expect((await request.post(`/api/services/${service.id}/archive`, { headers: adminHeaders })).status()).toBe(200)
  await page.getByRole('button', { name: 'Salvar rascunho' }).click()
  await expect(page.getByRole('alert')).toBeVisible()
  await expect(page.getByLabel('Descrição da venda')).toHaveValue('Venda do operador')
  expect((await request.post(`/api/services/${service.id}/restore`, { headers: adminHeaders })).status()).toBe(200)
  await page.getByRole('button', { name: 'Salvar rascunho' }).click()
  await expect(page.getByRole('button', { name: 'Concluir venda' })).toBeEnabled()
  await expect(page.getByRole('button', { name: 'Cancelar venda' })).toHaveCount(0)
  await confirm(page, 'Concluir venda')
  await page.getByRole('button', { name: 'Sair da conta' }).click()
  await expect(page.getByRole('heading', { name: 'Bom ter você aqui.' })).toBeVisible()
  await account(page, request, `other-${info.project.name}`)
  for (const route of [`/vendas/${id}`, `/precificacao/${rule.id}`]) {
    await page.goto(route)
    await expect(page.getByRole('alert')).toContainText('Não encontramos este registro')
  }
})

test('listagens: paginação, busca de regras e período/status de vendas', async ({ page, request }, info) => {
  const { headers } = await account(page, request, `lists-${info.project.name}`)
  for (let index = 0; index < 11; index++) {
    await request.post('/api/pricing-rules', { headers, data: { name: `Regra ${index}`, strategy_key: 'manual' } })
    await request.post('/api/sales', { headers, data: { description: `Venda ${index}`, occurred_at: '2026-09-16T12:00:00-03:00', final_total: '0' } })
  }
  await page.goto('/precificacao')
  await expect(page.getByLabel('Paginação')).toContainText('11 registros')
  await page.getByRole('button', { name: 'Próxima página' }).click()
  await expect(page.getByLabel('Paginação')).toContainText('Página 2')
  await page.getByLabel('Buscar regras').fill('Regra 10')
  await page.getByRole('button', { name: 'Filtrar', exact: true }).click()
  await expect(page.getByLabel('Paginação')).toContainText('1 registro')
  await page.goto('/vendas')
  await expect(page.getByLabel('Paginação')).toContainText('11 registros')
  await page.getByRole('button', { name: 'Próxima página' }).click()
  await expect(page.getByLabel('Paginação')).toContainText('Página 2')
  await page.getByLabel('Início (inclusivo)').fill('2026-09-16T00:00:00-03:00')
  await page.getByLabel('Fim (exclusivo)').fill('2026-09-16T12:00:00-03:00')
  await page.getByRole('button', { name: 'Filtrar vendas' }).click()
  await expect(page.getByRole('heading', { name: 'Nenhuma venda encontrada.' })).toBeVisible()
  await page.getByRole('button', { name: 'Limpar filtros' }).click()
  await expect(page).toHaveURL(/\/vendas$/)
  await expect(page.getByLabel('Paginação')).toContainText('11 registros')
  await page.getByLabel('Status', { exact: true }).selectOption('completed')
  await page.getByRole('button', { name: 'Filtrar vendas' }).click()
  await expect(page.getByRole('heading', { name: 'Nenhuma venda encontrada.' })).toBeVisible()
})
